"use client";

import {useMemo,useRef,useState} from "react";
import {IMPORT_FIELDS,IMPORT_TEMPLATE,IMPORT_RESEARCH_PROMPT,IMPORT_MAX_CHARACTERS,parseSpeciesImport,type ImportField} from "@/lib/species-quick-import";
import styles from "@/app/admin/species/ledger-desk.module.css";

type ImportMode="empty"|"replace";
function findControl(form:HTMLFormElement,name:string):HTMLInputElement|HTMLTextAreaElement|HTMLSelectElement|null{
 return Array.from(form.elements).find(item=>(item instanceof HTMLInputElement||item instanceof HTMLTextAreaElement||item instanceof HTMLSelectElement)&&item.name===name) as HTMLInputElement|HTMLTextAreaElement|HTMLSelectElement|null;
}
function writeInput(control:HTMLInputElement|HTMLTextAreaElement|HTMLSelectElement,value:string){
 // Preserve React's onChange handling when the field happens to be controlled.
 const prototype=control instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:control instanceof HTMLSelectElement?HTMLSelectElement.prototype:HTMLInputElement.prototype;
 const setter=Object.getOwnPropertyDescriptor(prototype,"value")?.set;
 if(setter)setter.call(control,value);else control.value=value;
 control.dispatchEvent(new Event("input",{bubbles:true}));
 control.dispatchEvent(new Event("change",{bubbles:true}));
}

export function LedgerQuickImport({recordId}:{recordId:string}){
 const [open,setOpen]=useState(false);
 const [source,setSource]=useState("");
 const [mode,setMode]=useState<ImportMode>("empty");
 const [feedback,setFeedback]=useState("");
 const textarea=useRef<HTMLTextAreaElement>(null);
 const parsed=useMemo(()=>source.trim()?parseSpeciesImport(source):null,[source]);
 const form=()=>document.getElementById("ledger-species-editor") as HTMLFormElement|null;
 const fields=IMPORT_FIELDS.map(([field,label])=>{
  const incoming=parsed?.values[field];
  const existing=form()?new FormData(form()!).get(field):null;
  const saved=typeof existing==="string"?existing:"";
  const hasValue=Boolean(incoming);
  const willReplace=hasValue&&Boolean(saved.trim());
  return {field,label,incoming,willReplace,include:hasValue&&(mode==="replace"||!saved.trim())};
 }).filter(item=>item.incoming);
 const included=fields.filter(item=>item.include);
 const groupControl=form()?new FormData(form()!).get("organismGroup"):null;
 const groupMismatch=Boolean(parsed?.values.organismGroup&&groupControl&&parsed.values.organismGroup!==groupControl);
 const apply=()=>{
  const editor=form();
  if(!editor||!parsed||parsed.error||!included.length){setFeedback("No importable changes to apply.");return;}
  if(groupMismatch){setFeedback("Choose a matching organism group in Identity before importing this profile. No fields were applied.");return;}
  let count=0;
  const traitsToApply: string[]=[];
  for(const item of included){
   if(item.field==="notableTraits"){
    traitsToApply.push(...(item.incoming||"").split("\n").filter(Boolean));count++;continue;
   }
   const control=findControl(editor,item.field);
   if(!control)continue;
   if(control instanceof HTMLSelectElement && !Array.from(control.options).some(option=>option.value===item.incoming))continue;
   writeInput(control,item.incoming||"");count++;
  }
  if(traitsToApply.length){
   window.dispatchEvent(new CustomEvent("podscape-ledger-traits-import",{detail:{traits:traitsToApply}}));
  }
  window.dispatchEvent(new Event("podscape-ledger-import-applied"));
  setFeedback(count+" field"+(count===1?"":"s")+" applied to your unsaved record. Review the guided steps, then press Save changes. Publication settings were not changed.");
  setOpen(false);
 };
 const dismiss=()=>{setOpen(false);setFeedback("")};
 return <div className={styles.quickImportRoot}>
  <div className={styles.quickImportEntry}>
   <div><strong>Species Quick Import</strong><small>Research with the exact field contract. Nothing is silently shortened.</small></div>
   <button type="button" onClick={()=>{setFeedback("");setOpen(value=>!value)}} aria-expanded={open}>{open?"Close import":"+ Quick Import"}</button>
  </div>
  {feedback?<p role="status" className={styles.quickImportSuccess}>{feedback}</p>:null}
  {open?<div className={styles.quickImportPanel}>
    <div className={styles.quickImportTop}><strong>Import researched species data</strong><button type="button" onClick={dismiss} aria-label="Close Quick Import">×</button></div>
    <p>Paste a JSON profile generated by ChatGPT or another trusted source. Every value is subject to review. Identity verification, publication, catalogue ID and photos can never be changed by import.</p>
    <p>Springtail profiles are supported. Start with New springtail record, or select Springtails in Identity before importing. The JSON organismGroup must match the editor.</p>
    <p><strong>{IMPORT_FIELDS.length} supported import fields</strong> · {IMPORT_MAX_CHARACTERS.toLocaleString("en-CA")} characters maximum · long text is preserved or rejected, never cut off. Empty fields are allowed.</p><label htmlFor="ledger-import-json">Species JSON</label>
    <textarea id="ledger-import-json" ref={textarea} rows={7} value={source} onChange={event=>{setSource(event.target.value);setFeedback("")}} placeholder={'{"commonName":"Dairy Cow","scientificName":"Porcellio cf. laevis","careLevel":"Beginner"}'} spellCheck={false}/>
    <div className={styles.quickImportTools}>
      <button type="button" onClick={async()=>{try{await navigator.clipboard.writeText(IMPORT_TEMPLATE);setFeedback("Blank import template copied.");}catch{setSource(IMPORT_TEMPLATE);textarea.current?.focus();setFeedback("Template inserted for copying.");}}}>Copy blank JSON template</button>
      <button type="button" onClick={async()=>{try{await navigator.clipboard.writeText(IMPORT_RESEARCH_PROMPT);setFeedback("Research prompt copied — includes every field name, limit and sourcing requirement.");}catch{setFeedback("Clipboard unavailable. Use the JSON template and research contract shown here.");}}}>Copy research prompt</button><button type="button" onClick={()=>{setSource("");setFeedback("")}}>Clear</button>
    </div>
    {parsed?.error?<p className={styles.quickImportError} role="alert">{parsed.error}</p>:null}
    {groupMismatch?<p className={styles.quickImportError} role="alert">This JSON is for a different organism group. Choose the matching group in Identity, then reopen Quick Import. Nothing will be applied until they match.</p>:null}
    {parsed?.warnings.length?<div className={styles.quickImportWarnings} role="status"><strong>Import validation details</strong>{parsed.warnings.map((warning,index)=><p key={index}>{warning}</p>)}</div>:null}
    {parsed&&!parsed.error?<div className={styles.quickImportReview}>
      <h3>Review recognized fields</h3>
      <div className={styles.quickImportModes} role="group" aria-label="Existing field handling">
       <label><input type="radio" name="ledger-import-mode" checked={mode==="empty"} onChange={()=>setMode("empty")}/> Fill empty fields only</label>
       <label><input type="radio" name="ledger-import-mode" checked={mode==="replace"} onChange={()=>setMode("replace")}/> Replace existing values</label>
      </div>
      <p>{included.length} field{included.length===1?"":"s"} ready to apply · {fields.length-included.length} skipped</p>
      <div className={styles.quickImportRows}>{fields.map(row=><div key={row.field} className={row.include?styles.quickImportRow:styles.quickImportRowSkipped}><div><strong>{row.label}</strong><span>{row.incoming?.replaceAll("\n"," · ")}</span></div><small>{!row.include?"Keeping existing value":row.willReplace?"Will replace existing value":"Will fill field"}</small></div>)}</div>
      
      <button type="button" className={styles.quickImportApply} disabled={!included.length||groupMismatch} onClick={apply}>Apply {included.length} field{included.length===1?"":"s"} to editor →</button>
      <small>No record is saved or published until you explicitly save it.</small>
    </div>:null}
  </div>:null}
 </div>;
}
