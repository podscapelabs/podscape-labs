-- Ranking rewards: permanent achievements and repeatable EXP are separate.
-- UTC seasons, opted-in players only, no purchases, no Pod Coins.
alter table public.fun_zone_ranking_preferences
 add column if not exists reward_opted_in_at timestamptz;
update public.fun_zone_ranking_preferences set reward_opted_in_at=now()
 where public_enabled=true and reward_opted_in_at is null;

create table if not exists public.fun_zone_ranking_awards (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 board_key text not null,
 period_key text not null check (period_key in ('daily','weekly','monthly','all-time')),
 period_start timestamptz not null,
 placement integer not null check (placement between 1 and 3),
 exp_awarded integer not null check (exp_awarded > 0),
 awarded_at timestamptz not null default now(),
 unique(user_id,board_key,period_key,period_start,placement)
);
alter table public.fun_zone_ranking_awards enable row level security;
revoke all on public.fun_zone_ranking_awards from anon,authenticated;
create index if not exists ranking_awards_user_idx on public.fun_zone_ranking_awards(user_id,awarded_at desc);

create table if not exists public.fun_zone_ranking_settlements (
 board_key text not null,
 period_key text not null check (period_key in ('daily','weekly','monthly')),
 period_start timestamptz not null,
 settled_at timestamptz not null default now(),
 primary key(board_key,period_key,period_start)
);
alter table public.fun_zone_ranking_settlements enable row level security;
revoke all on public.fun_zone_ranking_settlements from anon,authenticated;

create or replace function public.settle_fun_zone_rankings(p_now timestamptz default now())
returns integer
language plpgsql security definer set search_path=public
as $$
declare
 v_period text; v_start timestamptz; v_end timestamptz;
 v_board text; v_row record; v_exp integer;
 v_event text; v_count integer:=0; v_prior integer;
 v_key text; v_game_awards integer;
begin
 if auth.role() is distinct from 'service_role' then
  raise exception 'Service role required';
 end if;
 perform pg_advisory_xact_lock(hashtext('settle_fun_zone_rankings_v1'));
 foreach v_period in array array['daily','weekly','monthly'] loop
  v_end:=case v_period
    when 'daily' then date_trunc('day',p_now at time zone 'UTC') at time zone 'UTC'
    when 'weekly' then date_trunc('week',p_now at time zone 'UTC') at time zone 'UTC'
    else date_trunc('month',p_now at time zone 'UTC') at time zone 'UTC' end;
  v_start:=case v_period
    when 'daily' then v_end-interval '1 day'
    when 'weekly' then v_end-interval '7 days'
    else v_end-interval '1 month' end;
  -- Avoid retroactive awards for seasons that finished before launch.
  if v_end <= '2026-11-11T00:00:00Z'::timestamptz then continue; end if;
  for v_board in
   select board from (
    select 'all'::text as board
    union all
    select unnest(array['crossword-colony','colony-connections','word-burrow',
     'species-detective','keepers-challenge','word-of-the-week','species-quiz','word-search'])::text
   ) b order by case when board='all' then 0 else 1 end,board
  loop
   -- Snapshot a closed board once, even if all its participants have zero points.
   insert into public.fun_zone_ranking_settlements(board_key,period_key,period_start)
    values(v_board,v_period,v_start) on conflict do nothing;
   if not found then continue; end if;
   for v_row in
    with scores as (
     select c.user_id,count(*)::integer as completions
      from public.member_puzzle_completions c
      join public.fun_zone_ranking_preferences f on f.user_id=c.user_id
       and f.public_enabled and f.reward_opted_in_at is not null
       and f.reward_opted_in_at < v_end
      where c.completed_at>=v_start and c.completed_at<v_end
       and (v_board='all' or c.game_key=v_board)
      group by c.user_id
    ), ranks as (
     select user_id,completions,
      rank() over(order by completions desc)::integer as place,
      count(*) over()::integer as participants from scores
    )
    select user_id,place from ranks where place<=3 and participants>=2
    order by place,user_id
   loop
    v_exp:=case v_period
      when 'daily' then case v_row.place when 1 then 50 when 2 then 30 else 15 end
      when 'weekly' then case v_row.place when 1 then 200 when 2 then 125 else 75 end
      else case v_row.place when 1 then 500 when 2 then 300 else 175 end end;
    if v_board<>'all' then
     -- At most two game-specific rewards per member per closed period.
     select count(*) into v_game_awards from public.fun_zone_ranking_awards
      where user_id=v_row.user_id and period_key=v_period and period_start=v_start
       and board_key<>'all';
     if v_game_awards>=2 then continue; end if;
     v_exp:=greatest(1,round(v_exp*0.25)::integer);
    end if;
    v_event:=format('ranking:%s:%s:%s',v_period,v_board,to_char(v_start at time zone 'UTC','YYYYMMDD'));
    insert into public.member_progress_events(user_id,event_key,source,exp_delta,coin_delta)
     values(v_row.user_id,v_event,'ranking',v_exp,0) on conflict do nothing;
    if not found then continue; end if;
    insert into public.fun_zone_ranking_awards(user_id,board_key,period_key,period_start,placement,exp_awarded)
     values(v_row.user_id,v_board,v_period,v_start,v_row.place,v_exp);
    insert into public.member_progress(user_id,total_exp,pod_coins)
     values(v_row.user_id,v_exp,0) on conflict(user_id) do update
      set total_exp=public.member_progress.total_exp+excluded.total_exp,updated_at=now();
    insert into public.member_achievements(user_id,achievement_key)
     values(v_row.user_id,'ranking_first_podium') on conflict do nothing;
    if v_period='weekly' and v_row.place=1 then
     insert into public.member_achievements(user_id,achievement_key)
      values(v_row.user_id,'ranking_weekly_champion') on conflict do nothing;
    end if;
    if v_row.place=1 and (select count(distinct (period_key,period_start)) from public.fun_zone_ranking_awards
      where user_id=v_row.user_id and placement=1 and period_key<>'all-time')>=3 then
     insert into public.member_achievements(user_id,achievement_key)
      values(v_row.user_id,'ranking_three_wins') on conflict do nothing;
    end if;
    v_count:=v_count+1;
   end loop;
  end loop;
 end loop;
 -- All-time podium milestones: one payout for each *improvement*, not once per day.
 for v_board in select board from (
    select 'all'::text as board
    union all select unnest(array['crossword-colony','colony-connections','word-burrow',
      'species-detective','keepers-challenge','word-of-the-week','species-quiz','word-search'])::text
    ) b order by case when board='all' then 0 else 1 end,board
 loop
  for v_row in
   with scores as (
    select c.user_id,count(*)::integer as completions
     from public.member_puzzle_completions c
     join public.fun_zone_ranking_preferences f on f.user_id=c.user_id
      and f.public_enabled and f.reward_opted_in_at is not null
     where v_board='all' or c.game_key=v_board
     group by c.user_id
   ), ranks as (
    select user_id,rank() over(order by completions desc)::integer as place,
     count(*) over()::integer as participants from scores
   )
   select user_id,place from ranks where place<=3 and participants>=2
   order by place,user_id
  loop
   v_exp:=case v_row.place when 1 then 750 when 2 then 450 else 250 end;
   if v_board<>'all' then
    select count(distinct board_key) into v_game_awards
    from public.fun_zone_ranking_awards
    where user_id=v_row.user_id and period_key='all-time' and board_key<>'all'
     and board_key<>v_board;
    if v_game_awards>=2 and not exists (
     select 1 from public.fun_zone_ranking_awards where user_id=v_row.user_id
      and period_key='all-time' and board_key=v_board
    ) then continue; end if;
    v_exp:=round(v_exp*0.25)::integer;
   end if;
   select coalesce(max(case placement when 1 then 750 when 2 then 450 else 250 end),0)
    into v_prior from public.fun_zone_ranking_awards
    where user_id=v_row.user_id and board_key=v_board and period_key='all-time';
   if v_board<>'all' then v_prior:=round(v_prior*0.25)::integer; end if;
   if v_exp<=v_prior then continue; end if;
   v_exp:=v_exp-v_prior;
   v_event:=format('ranking:all-time:%s:%s',v_board,v_row.place);
   insert into public.member_progress_events(user_id,event_key,source,exp_delta,coin_delta)
    values(v_row.user_id,v_event,'ranking',v_exp,0) on conflict do nothing;
   if not found then continue; end if;
   insert into public.fun_zone_ranking_awards(user_id,board_key,period_key,period_start,placement,exp_awarded)
    values(v_row.user_id,v_board,'all-time','epoch'::timestamptz,v_row.place,v_exp)
    on conflict do nothing;
   insert into public.member_progress(user_id,total_exp,pod_coins)
    values(v_row.user_id,v_exp,0) on conflict(user_id) do update
     set total_exp=public.member_progress.total_exp+excluded.total_exp,updated_at=now();
   insert into public.member_achievements(user_id,achievement_key)
    values(v_row.user_id,'ranking_first_podium') on conflict do nothing;
   if v_row.place=1 then
    insert into public.member_achievements(user_id,achievement_key)
     values(v_row.user_id,'ranking_alltime_top') on conflict do nothing;
   end if;
   v_count:=v_count+1;
  end loop;
 end loop;
 return v_count;
end;
$$;
revoke all on function public.settle_fun_zone_rankings(timestamptz) from public,anon,authenticated;
grant execute on function public.settle_fun_zone_rankings(timestamptz) to service_role;
