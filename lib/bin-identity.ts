/** Display-only names: never rename a keeper's saved data automatically. */
export function binDisplayName(bin:{id:string;name:string;label?:string},species?:string){
 const name=/^primary (colony|enclosure|bin)$/i.test(bin.name.trim())?"Bin "+bin.id.slice(-6).toUpperCase():bin.name;
 return [species,name,bin.label].filter(Boolean).join(" · ");
}

/** A member's bin has a technical identity and an organism identity.
 * Collection cards lead with the organism/morph rather than a generated UUID fragment.
 * Do not mutate a stored keeper_enclosures.name or change routes/QR identifiers.
 */
export type BinSpeciesIdentity={
 commonName?:string|null;morph?:string|null;scientificName?:string|null;
 genus?:string|null;species?:string|null;
};
export function binCardIdentity(bin:{name:string;label?:string},record?:BinSpeciesIdentity|null){
 const name=(bin.name||"").trim();
 const morph=(record?.morph||"").trim();
 const common=(record?.commonName||"").trim();
 const isGenerated=/^(?:primary (?:colony|enclosure|bin)|bin [a-f0-9]{6})$/i.test(name);
 const title=morph||common||(!isGenerated?name:"Colony");
 const scientific=(record?.scientificName||"").trim()||
  [record?.genus?.trim(),record?.species?.trim()].filter(Boolean).join(" ")||"Scientific identity unavailable";
 // A real custom bin name is useful as a third line, particularly for multiple
 // enclosures of the same morph. Never render an autogenerated UUID as its title.
 const binName=!isGenerated&&name.toLocaleLowerCase()!==title.toLocaleLowerCase()?name:"";
 return{title,scientific,binName,location:(bin.label||"").trim()};
}
