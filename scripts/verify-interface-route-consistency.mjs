import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");

const routing=read("lib/interface-route-policy.ts");
const authPaths=["/","/auth/","/early-access","/account/login","/account/sign-up","/account/register","/account/forgot-password","/account/change-password","/account/reset-password","/admin","/admin/forgot-password","/admin/reset-password"];
for(const name of authPaths)assert.ok(routing.includes('"' + name + '"')||name==="/auth/"&&routing.includes('"/auth/"'),"All standalone auth routes must be excluded from global chrome: "+name);
assert.match(routing,/export function isStandaloneAccessRoute/);
assert.match(routing,/export function feedbackAllowedOnRoute/);
const mobile=read("components/GlobalMobileNav.tsx");
const feedback=read("components/FloatingFeedback.tsx");
const theme=read("components/OwnerThemeQuickSwitcher.tsx");
assert.match(mobile,/isStandaloneAccessRoute\(pathname\)/,"Mobile navigation follows universal route policy");
assert.match(feedback,/feedbackAllowedOnRoute\(pathname\)/,"Feedback follows universal route policy");
assert.match(theme,/isStandaloneAccessRoute\(pathname\)/,"Owner theme tester follows universal route policy");
assert.doesNotMatch(mobile,/const authPaths=/,"Mobile nav cannot maintain a conflicting access list");
assert.doesNotMatch(feedback,/const excluded=pathname===/,"Feedback cannot maintain a conflicting access list");
assert.match(feedback,/useEffect\(\(\)=>\{setOpen\(false\)\},\[pathname\]\)/,"Feedback sheet must close when navigating");
assert.match(feedback,/previousOverflow=document\.body\.style\.overflow/,"Feedback should preserve the previous scroll lock");
assert.match(feedback,/document\.body\.style\.overflow=previousOverflow/,"Feedback must restore previous scroll lock");
assert.match(feedback,/if\(sendingRef\.current\)return/,"Escape cannot dismiss an in-flight feedback submission");
const rail=read("components/PortalActionRail.tsx");
assert.match(rail,/if\(action\.disabled\)return <span/,"Disabled link actions must not navigate");
assert.match(rail,/aria-disabled="true"/,"Disabled contextual actions have semantic disabled state");
assert.match(rail,/<Link href=\{action\.href\}/,"Working shortcuts remain navigable");
assert.match(rail,/<button key=\{action\.label\}/,"In-place workflows remain usable");
const railCss=read("components/PortalActionRail.module.css");
assert.match(railCss,/\.action,\.disabled\{flex:1 1 calc\(50% - 7px\)/,"Disabled and enabled actions keep equal mobile dimensions");
const guard=read("components/OwnerDeskUnsavedGuard.tsx");
assert.match(guard,/No unsaved edits/,"Unsaved-edit guard must not falsely claim a save");
assert.match(guard,/Unsaved changes/,"Dirty edits must be visible");
assert.doesNotMatch(guard,/All changes saved/,"Only server-confirmed saves may say saved");
const keeperWorkflow=read(".github/workflows/keeper-qa.yml");
assert.match(keeperWorkflow,/name: Universe-wide Owner Studio and contextual navigation checks\s+run: \|\s+node scripts\/verify-universe-polish\.mjs\s+node scripts\/verify-universe-consistency-audit\.mjs\s+node scripts\/verify-universe-interactions\.mjs/,"Keeper workflow must execute each consistency script as a separate command");
console.log("Global interface consistency checks passed: auth route policy, feedback lifetime, modal Escape, disabled controls, editing status and Keeper CI.");
