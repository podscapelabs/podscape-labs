import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const admin=read("lib/supabase-admin.ts");
const vendor=read("app/shop/vendors/actions.ts");
const updates=read("app/admin/updates/actions.ts");
const prefs=read("app/api/preferences/sync/route.ts");
const model=read("lib/podscape-updates.ts");
const directory=read("app/shop/vendors/page.tsx");
const application=read("app/shop/vendors/apply/page.tsx");
const workflow=read(".github/workflows/keeper-qa.yml");

assert.match(admin,/import "server-only"/,"Admin Supabase client must stay server-only");
assert.ok(!/NEXT_PUBLIC_/.test(admin),"Never use public environment keys for privileged client");
assert.match(vendor,/await requireCustomerPreviewAccess\(\)/,"Vendor submission access must be checked");
assert.match(vendor,/db\.auth\.getUser\(\)/,"Vendor submissions must verify the authenticated user");
assert.match(vendor,/!user\.email_confirmed_at/,"Vendor submissions must require verified member emails");
assert.match(vendor,/\.eq\("user_id",user\.id\)/,"Vendor edits must scope to verified member ownership");
assert.match(vendor,/status:"pending"/,"Vendor modifications must revoke prior approval");
assert.match(vendor,/isAdminAuthenticated\(\)/,"Vendor approval actions must authorize the owner");
assert.match(updates,/isAdminAuthenticated\(\)/,"Platform update publishing must authorize the owner");
assert.match(updates,/validDestination\(href\)/,"Release links must remain internal and validated");
assert.match(model,/\.eq\("status","published"\)/,"Public updates cannot include private drafts");
assert.match(directory,/\.eq\("status","approved"\)/,"Public vendors cannot include pending applications");
assert.match(application,/\.eq\("user_id",user\.id\)/,"Vendor edit form must load only the current user's draft");
assert.match(prefs,/db\.auth\.getUser\(\)/,"Preference sync must verify the session");
assert.match(prefs,/\.eq\("user_id",session\.userId\)/,"Preference sync must be member-scoped");
assert.match(prefs,/\.eq\("revision",revision\)/,"Preference writes must use optimistic revision checking");
assert.match(workflow,/verify-stabilization-boundaries\.mjs/,"Stabilization gates must run during pre-deploy CI");
console.log("Stabilization boundary assertions passed: privileged credentials, vendor isolation, update publishing and preference sync.");
