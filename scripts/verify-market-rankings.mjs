import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const sql=read("supabase/migrations/202611110006_exchange_market_rankings.sql");
const api=read("app/api/fun-zone/pod-exchange/rankings/route.ts");
const cron=read("app/api/cron/exchange-market-rankings/route.ts");
