import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import ts from "typescript";
const read=path=>readFileSync(resolve(path),"utf8");
const sql=read("supabase/migrations/20261110230000_pod_exchange_achievements.sql");
const route=read("app/api/fun-zone/pod-exchange/route.ts");
const walletSql=read("supabase/migrations/20261110234500_pod_exchange_persistent_portfolios.sql");

const ui=read("app/fun-zone/pod-exchange/PodExchange.tsx");
const catalogJs=ts.transpileModule(read("data/achievement-catalog.ts"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
new Function("exports",catalogJs)(exports);
const achievements=exports.achievementCatalog;
const expected={exchange_first_trade:15,exchange_first_sale:20,exchange_five_trades:30,exchange_three_companies:35,exchange_fifteen_trades:60};
assert.equal(new Set(achievements.map(a=>a.key)).size,achievements.length);
for(const [key,exp] of Object.entries(expected)){
 const item=achievements.find(a=>a.key===key);
 assert.ok(item,"Missing "+key);
 assert.equal(item.exp,exp);
 assert.ok(item.exp>0,"Trade milestones continue to award EXP");
 assert.equal(item.status,"available");
 assert.equal(item.href,"/fun-zone/pod-exchange");
 assert.ok(sql.includes("'"+key+"'"),"Milestone tracked server-side: "+key);
}
assert.match(sql,/enable row level security/i);
assert.match(sql,/auth\.uid\(\)\)=user_id/);
assert.match(sql,/primary key\(user_id,trade_id\)/);
assert.match(sql,/pg_advisory_xact_lock/);
assert.match(sql,/on conflict do nothing/i);
assert.match(sql,/coin_delta\)\s*values\([^;]+,0\)/i);
assert.match(sql,/grant execute on function public\.record_member_exchange_trade\(uuid,text,text,text,integer,bigint\) to service_role/i);
assert.match(route,/db\.auth\.getUser\(\)/);
assert.match(route,/email_confirmed_at/);
assert.match(route,/testerAccessStatus/);
assert.match(route,/quoteForCycle\(engine,trade.symbol,trade.cycle\)/,"Server verifies version-aware shared prices against the execution request");
assert.match(route,/serverQuote!==trade.unitPrice/,"Server must reject stale or forged trade prices");
assert.match(route,/Math\.abs\(arcadeCycleAt\(Date\.now\(\)\)-trade\.cycle\)>0/,"Server validates one-minute tagged trade cycles");
assert.match(route,/admin!\.rpc\("execute_member_exchange_order"/);
assert.match(walletSql,/public\.record_member_exchange_trade\(/);
assert.match(walletSql,/member_exchange_portfolios/);
assert.match(walletSql,/member_exchange_orders/);
assert.match(walletSql,/for update/);
assert.match(walletSql,/primary key\(user_id,trade_id\)/);
assert.match(walletSql,/p_trades jsonb/);
assert.match(ui,/announceAchievement\(notice\)/);
assert.match(ui,/if\(!response\.ok\|\|!data\.exists\|\|!data\.portfolio\)/);
assert.match(ui,/action:"trade",trade/);
assert.ok(ui.includes("decodeSavedPortfolio"),"Prior beta wallet loading is guarded against silent resets");
assert.ok(ui.includes("const OWNER_KEY=STORAGE_KEY"),"Local beta wallet bound to signed-in identity");
assert.ok(ui.includes("owner&&owner!==userId"),"An old account wallet cannot be imported into a different account");
assert.ok(ui.includes("const GUEST_KEY=STORAGE_KEY"),"Guest wallets segregated after account login");
assert.ok(ui.includes("localWalletForAccount(state.userId)"),"Legacy imports use server-confirmed owner");
assert.ok(ui.includes("if(!state.userId)throw"),"No import without known account");
const watchlist=read("app/fun-zone/PodExchangeWatchlist.tsx");
assert.ok(watchlist.includes("owner&&owner!==data.userId"),"Watchlist prevents cross-account wallet leak");
assert.ok(route.includes("userId:auth.user!.id")&&route.includes("userId:user!.id"),"Wallet APIs include verified account ID");
assert.ok(!route.includes('"/api/progress/exchange-trade"'),"No separate spoofable achievement route");
console.log("Pod Exchange achievements: five unique EXP-only milestones, native toast, scoped server validation and idempotent RLS ledger verified.");
