import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const loadedModule={exports:{}};
vm.runInNewContext(ts.transpileModule(readFileSync("lib/collection-views.ts","utf8"),{compilerOptions:{loadedModule:ts.ModuleKind.CommonJS}}).outputText,{exports:loadedModule.exports,module:loadedModule});
const {resolveCollectionView:resolve,speciesMatchesCollectionView:matches}=loadedModule.exports;
const bins=[{speciesId:"active",isArchived:false},{speciesId:"archived",isArchived:true}];
const saved=new Set(["active","archived","bookmark"]);
assert.equal(matches("bookmark","active",saved,bins),false);
assert.equal(matches("bookmark","saved",saved,bins),true);
assert.equal(matches("archived","active",saved,bins),false);
assert.equal(matches("archived","saved",saved,bins),false);
assert.equal(matches("archived","archived",saved,bins),true);
assert.equal(matches("active","active",saved,bins),true);
assert.equal(resolve(undefined,"bookmark",bins),"saved");
assert.equal(resolve(undefined,"archived",bins),"archived");
assert.equal(resolve(undefined,"active",bins),"active");
assert.equal(resolve("active","bookmark",bins),"active");
assert.equal(resolve(undefined,undefined,bins),"active");
assert.equal(matches("unsaved","saved",saved,bins),false);
console.log("Collection views: bookmarks excluded from colonies, archived separation, and last-bin return routing passed.");
const setupModule={exports:{}};
vm.runInNewContext(ts.transpileModule(readFileSync("lib/bin-setup.ts","utf8"),{compilerOptions:{loadedModule:ts.ModuleKind.CommonJS}}).outputText,{exports:setupModule.exports,loadedModule:setupModule});
const {nextBinName}=setupModule.exports;
assert.equal(nextBinName("Panda King",[]),"Panda King · Bin 01");
assert.equal(nextBinName("Panda King",["Panda King · Bin 01","Panda King · Bin 02"]),"Panda King · Bin 03");
assert.equal(nextBinName("Panda King",["panda king · bin 01"]),"Panda King · Bin 02");
assert.equal(nextBinName("Panda King",["Panda King · Bin 02"]),"Panda King · Bin 01");
assert.ok(nextBinName("x".repeat(120),[]).length<=80);
console.log("Bin name suggestions: uniqueness, numbering gaps, case handling and field limits passed.");
