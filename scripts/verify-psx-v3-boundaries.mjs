import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=path=>readFileSync(path,"utf8");

const engine=read("lib/psx-v3-prototype.mjs");
const privateService=read("lib/psx-v3-preview-server.ts");
const marketService=read("lib/psx-v3-market-server.ts");
const preview=read("app/api/fun-zone/pod-exchange/v3-preview/route.ts");
const history=read("lib/psx-v3-history-server.ts");
const migration=read("supabase/migrations/20261112180000_psx_v3_versioned_history.sql");
const oldEngine=read("lib/pod-exchange.ts");
const oldTrade=read("app/api/fun-zone/pod-exchange/route.ts");
const ledger=read("lib/exchange-ranking-audit.ts");
const page=read("app/fun-zone/pod-exchange/PodExchange.tsx");

assert.match(engine,/from "node:crypto"/,"V3 uses Node-only HMAC rather than public PRNG seeds");
assert.match(history,/import "server-only"/,"V3 history persistence can only be called from trusted server code");
assert.match(history,/cutoverCycle\+lastMinute>nowCycle/,"Never persist unreleased price frames");
assert.match(history,/ignoreDuplicates:true/g,"Retries must preserve existing immutable history");
assert.doesNotMatch(history,/member_exchange_portfolios|member_exchange_orders/,"History materializer cannot mutate investor wallets or orders");
assert.match(privateService,/import "server-only"/,"Preview module never bundles into the client");
assert.match(preview,/Owner access required/,"Only owner sees market prototype");
assert.match(preview,/PSX_V3_PREVIEW_ENABLED/,"Preview can only be enabled by explicit server environment");
assert.match(privateService,/PSX_V3_SECRET/,"Private seed stays in server environment");
assert.match(privateService,/seed_fingerprint/,"Version validates seed fingerprint before returning a quote");
assert.match(privateService,/timingSafeEqual/,"Fingerprint comparison uses constant-time comparison");
assert.match(privateService,/priceMap\(row.opening_prices\)/,"Versioned opening anchors are required");
assert.match(privateService,/priceAt\(symbol,cutover-1\)/,"Cutover opening prices must match the last legacy closing price");
assert.match(engine,/minute===0\)return round\(openingPrice\)/,"V3 first minute must preserve opening anchor");
assert.match(engine,/rumourResolution:resolution/,"Resolution only becomes part of published frame after linked event");
assert.match(engine,/resolveRumour\(secret,currentSession,minute\)/,"Published rumour resolutions are generated from scheduled truth");
assert.doesNotMatch(page,/psx-v3-(prototype|preview)/,"Current client market stays on the historical engine");
assert.doesNotMatch(oldTrade,/psx-v3-(prototype|preview)/,"Live atomic trades must remain unchanged until rollout approval");
assert.match(oldTrade,/execute_member_exchange_order/,"Existing signed-in settlement RPC remains authoritative");
assert.match(ledger,/quoteForCycle\(active,symbol,cycle\)/,"Order audit chooses the stored engine version for every past cycle");
assert.match(marketService,/cycle<config.cutoverCycle\)return priceAt\(symbol,cycle\)/,"Cycles before V3 cutover always retain the original price formula");
assert.match(oldTrade,/quoteForCycle\(engine,trade.symbol,trade.cycle\)/,"Server verifies the actual published V3 or legacy quote before settlement");
assert.match(oldEngine,/ARCADE_CYCLE_TAG=1_000_000_000/,"Legacy minute-cycle namespace untouched");
assert.match(migration,/create table if not exists public.psx_market_versions/i);
assert.match(migration,/create table if not exists public.psx_market_price_history/i);
assert.match(migration,/create table if not exists public.psx_market_event_history/i);
assert.match(migration,/psx_price_history_immutable/,"Published snapshots are immutable");
assert.match(migration,/psx_version_pricing_immutable/,"Version release anchors cannot be silently changed");
assert.match(migration,/revoke all on public.psx_market_price_history from public,anon,authenticated/,"History does not have a public direct write/read grant");
assert.doesNotMatch(migration,/drop table/i,"Do not destroy existing tables");
assert.doesNotMatch(migration,/update public\.member_exchange_portfolios|delete from public\.member_exchange_orders|truncate/i,"Never reset live investor records");
assert.doesNotMatch(migration,/insert into public\.psx_market_versions/i,"Migration must not activate new market or create a cutover");
assert.doesNotMatch(migration,/execute_member_exchange_order|member_exchange_portfolios/i,"Prototype schema migration cannot modify live settlement");
console.log("PSX V3 private-server boundary and additive migration safety checks passed.");
